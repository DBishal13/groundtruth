#!/usr/bin/env bash
# Regenerates RESULTS.md by actually running the CLI against every fixture
# in this directory and capturing the real output. Run from repo root:
#   bash examples/fixtures/capture-results.sh > examples/fixtures/RESULTS.md
set -euo pipefail
cd "$(dirname "$0")/../.."

echo "# Fixture validation results"
echo
echo "Generated by [capture-results.sh](capture-results.sh) — real \`groundtruth validate\` output for every fixture in this directory, one good/bad pair per supported format. Regenerate with \`bash examples/fixtures/capture-results.sh > examples/fixtures/RESULTS.md\`."
echo

for f in examples/fixtures/*.geojson examples/fixtures/*.wkt examples/fixtures/*.kml examples/fixtures/*.gml examples/fixtures/*.shp examples/fixtures/*.gpkg; do
  name=$(basename "$f")
  echo "## \`$name\`"
  echo
  echo '```'
  npm run cli -- validate "$f" --type Polygon 2>&1 | grep -v "^>" | grep -v "^$" || true
  echo '```'
  echo
done
